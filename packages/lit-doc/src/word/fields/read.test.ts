import { expect, it } from 'vitest'
import { inspectDoc } from '../../inspection'
import { compoundFixture } from '../../testing/compound'
import { wordStreams } from '../../testing/word'
import { withFieldTables } from '../../testing/fields/document'
import type { FieldTableFixture } from '../../testing/fields/types'

const text = '\u0013PAGE\u00141\u0015\r'
const tokens = [{ position: 0, code: 19, value: 33 }, { position: 5, code: 20, value: 255 }, { position: 7, code: 21, value: 0x90 }]

/** @param tables - Independently declared source indexes. @param content - Author code units, not generated by a candidate reader. @returns Complete source bytes. */
function fixture(tables: readonly FieldTableFixture[] = [{ kind: 'main', tokens, terminal: 0xffffffff }], content = text): Uint8Array {
  return compoundFixture(withFieldTables(wordStreams([{ units: Array.from(content, char => char.charCodeAt(0)), unicode: false }]), tables))
}

it('retains raw index positions, ignores the terminal CP as a content bound and leaves formatting optional', () => {
  const bytes = fixture(), before = bytes.slice()
  const source = inspectDoc(bytes, { includeFields: true })
  expect(source.fields?.scope).toBe('field-index-source')
  expect(source.fields?.indexes).toHaveLength(7)
  const main = source.fields?.indexes.find(index => index.kind === 'main')
  expect(main).toMatchObject({ start: 0, end: 9, terminalCp: 0xffffffff, tokens: [
    { relativePosition: 0, nextRelativePosition: 5, code: 19, value: 33 },
    { relativePosition: 5, nextRelativePosition: 7, code: 20, value: 255 },
    { relativePosition: 7, nextRelativePosition: 0xffffffff, code: 21, value: 0x90 },
  ], entries: [{ start: 0, end: 8, separator: 5, indexDepth: 1, lastParsedType: 33,
    flags: { raw: 0x90, locked: true, hasSeparator: true, nested: false, privateResult: false } }] })
  expect(source.paragraphs).toBeUndefined()
  expect(source.diagnostics).toContainEqual(expect.objectContaining({ code: 'field-formatting-unresolved' }))
  expect(inspectDoc(bytes).fields).toBeUndefined()
  expect(bytes).toEqual(before)
})

it('keeps every document part relative while derived ranges use absolute source positions', () => {
  const kinds = ['main', 'footnote', 'header', 'comment', 'endnote', 'textbox', 'headerTextbox'] as const
  const content = text.repeat(7) + '\r'
  const streams = wordStreams([{ units: Array.from(content, char => char.charCodeAt(0)), unicode: false }], { storyLengths: Array(7).fill(9) })
  const actual = inspectDoc(compoundFixture(withFieldTables(streams, kinds.map(kind => ({ kind, tokens })))), { includeFields: true })
  expect(actual.fields?.indexes.map(index => [index.kind, index.start, index.entries[0]?.start, index.entries[0]?.end]))
    .toEqual(kinds.map((kind, index) => [kind, index * 9, index * 9, index * 9 + 8]))
})

it('retains nested fields in begin order and supports a field without a separator', () => {
  const content = '\u0013A\u0013B\u00141\u0015\u00142\u0015\r'
  const nested = [{ position: 0, code: 19, value: 7 }, { position: 2, code: 19, value: 8 },
    { position: 4, code: 20, value: 255 }, { position: 6, code: 21, value: 0xc0 },
    { position: 7, code: 20, value: 0 }, { position: 9, code: 21, value: 0x80 }]
  const result = inspectDoc(fixture([{ kind: 'main', tokens: nested }], content), { includeFields: true })
  expect(result.fields?.indexes[0]?.entries.map(field => [field.start, field.end, field.separator, field.indexDepth]))
    .toEqual([[0, 10, 7, 1], [2, 7, 4, 2]])
  const noResult = inspectDoc(fixture([{ kind: 'main', tokens: [{ position: 0, code: 19, value: 33 },
    { position: 5, code: 21, value: 0 }] }], '\u0013PAGE\u0015\r'), { includeFields: true })
  expect(noResult.fields?.indexes[0]?.entries[0]).toMatchObject({ start: 0, end: 6, separator: null, flags: { hasSeparator: false } })
})

it('keeps all end flags distinct without interpreting the separator payload', () => {
  const source = inspectDoc(fixture([{ kind: 'main', tokens: [...tokens.slice(0, 2), { position: 7, code: 21, value: 255 }] }]), { includeFields: true })
  expect(source.fields?.indexes[0]?.entries[0]?.flags).toEqual({ raw: 255, differ: true, zombieEmbed: true,
    resultsDirty: true, resultsEdited: true, locked: true, privateResult: true, nested: true, hasSeparator: true })
})

it('ignores the three reserved marker bits while retaining the complete original byte', () => {
  const actual = inspectDoc(fixture([{ kind: 'main', tokens: tokens.map(token => ({ ...token, code: token.code | 0xe0 })) }]), { includeFields: true })
  expect(actual.fields?.indexes[0]?.tokens.map(token => [token.rawCode, token.code])).toEqual([[0xf3, 19], [0xf4, 20], [0xf5, 21]])
})

it.each([
  { tokens: [{ position: 0, code: 20, value: 0 }] },
  { tokens: [{ position: 0, code: 19, value: 33 }] },
  { tokens: [tokens[0]!, tokens[1]!, { position: 6, code: 20, value: 0 }, tokens[2]!] },
  { tokens: [tokens[0]!, tokens[1]!, { position: 5, code: 21, value: 0 }] },
  { tokens: [{ position: 0, code: 18, value: 33 }, ...tokens.slice(1)] },
  { tokens: [{ position: 1, code: 19, value: 33 }, ...tokens.slice(1)] },
  { tokens: [...tokens, { position: 9, code: 19, value: 33 }] },
  { tokens, terminal: 7 },
])('refuses bad marker positions, order or topology %# while storage remains inspectable', table => {
  const bytes = fixture([{ kind: 'main', ...table }])
  expect(inspectDoc(bytes).text).toBe(text)
  expect(() => inspectDoc(bytes, { includeFields: true })).toThrow(expect.objectContaining({ code: 'invalid-field-data' }))
})

it('distinguishes absent and explicit empty tables without using the empty terminal as source text', () => {
  const actual = inspectDoc(fixture([{ kind: 'main', tokens: [], terminal: 0xffffffff }]), { includeFields: true })
  expect(actual.fields?.indexes[0]).toMatchObject({ terminalCp: 0xffffffff, tokens: [], entries: [] })
  expect(actual.fields?.indexes[1]).not.toHaveProperty('terminalCp')
})

it('bounds counts across document parts and nesting before allocating derived fields', () => {
  const content = text.repeat(2) + '\r'
  const streams = wordStreams([{ units: Array.from(content, char => char.charCodeAt(0)), unicode: false }], { storyLengths: [9, 9, 0, 0, 0, 0, 0] })
  const bytes = compoundFixture(withFieldTables(streams, [{ kind: 'main', tokens }, { kind: 'footnote', tokens }]))
  expect(() => inspectDoc(bytes, { includeFields: true, limits: { maxFields: 1 } }))
    .toThrow(expect.objectContaining({ code: 'limit-exceeded' }))
  const nested = fixture([{ kind: 'main', tokens: [{ position: 0, code: 19, value: 1 }, { position: 1, code: 19, value: 1 },
    { position: 2, code: 21, value: 64 }, { position: 3, code: 21, value: 0 }] }], '\u0013\u0013\u0015\u0015\r')
  expect(() => inspectDoc(nested, { includeFields: true, limits: { maxFieldDepth: 1 } }))
    .toThrow(expect.objectContaining({ code: 'limit-exceeded' }))
  expect(() => inspectDoc(fixture(), { includeFields: 'yes' as unknown as boolean }))
    .toThrow(expect.objectContaining({ code: 'invalid-input' }))
})
